import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';

// Only published, local contract documents may supply decoding syntax. No I/O
// occurs in the generated runtime module, and schema syntax grants no authority.
const directory = new URL('../packages/contracts/src/schemas/', import.meta.url);
const documents = new Map(['local-game-activity.schema.json', 'protocol-common.schema.json'].map(file => {
  const bytes = readFileSync(new URL(file, directory));
  const schema = JSON.parse(bytes);
  return [schema.$id, {schema, file, digest: createHash('sha256').update(bytes).digest('hex')}];
}));
const root = 'https://lifestream.dev/contracts/local-game-activity/1.0.0';
const used = new Set();
function expand(value, base, ancestors = []) {
  if (Array.isArray(value)) return value.map(child => expand(child, base, ancestors));
  if (value === null || typeof value !== 'object') return value;
  if ('$id' in value || '$dynamicRef' in value) throw new Error('Unsupported nested schema resource');
  if ('$ref' in value) {
    const absolute = new URL(value.$ref, base).href;
    if (ancestors.includes(absolute)) throw new Error('Recursive proposal schema reference');
    const [id, fragment] = absolute.split('#');
    const document = documents.get(id);
    if (!document || !fragment?.startsWith('/$defs/')) throw new Error(`Unpublished proposal schema reference: ${absolute}`);
    let target = document.schema;
    for (const part of fragment.slice(1).split('/')) {
      const key = decodeURIComponent(part).replaceAll('~1', '/').replaceAll('~0', '~');
      if (!Object.hasOwn(target, key)) throw new Error(`Missing proposal schema reference: ${absolute}`);
      target = target[key];
    }
    used.add(id);
    const resolved = expand(target, id, [...ancestors, absolute]);
    const siblings = Object.fromEntries(Object.entries(value).filter(([key]) => key !== '$ref'));
    return Object.keys(siblings).length ? {allOf: [resolved, expand(siblings, base, ancestors)]} : resolved;
  }
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, expand(child, base, ancestors)]));
}
const format = {type: 'json_schema', json_schema: {name: 'game_action_proposal', schema: {
  anyOf: [expand({$ref: '#/$defs/GameActionProposal'}, root), {type: 'null'}]
}}};
const output = [
  '// Generated by scripts/generate-game-response-format.mjs. Do not edit.',
  '// Contract syntax only; exact prepared identity, currentness and authority remain runtime obligations.',
  ...[...used].sort().map(id => `// ${documents.get(id).file} sha256:${documents.get(id).digest}`),
  "import type {InferenceResponseFormat} from './port.ts';",
  `const format:InferenceResponseFormat=${JSON.stringify(format, null, 2)};`,
  "function freeze<T>(value:T):T{if(value&&typeof value==='object'){for(const child of Object.values(value))freeze(child);Object.freeze(value);}return value;}",
  'export const gamePlanningResponseFormat=freeze(format);', ''
].join('\n');
const path = new URL('../packages/runtime/src/inference/game-response-format.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Game response format is stale; run node scripts/generate-game-response-format.mjs');
} else writeFileSync(path, output);
console.log(`Game response format: one proposal-or-null schema from ${used.size} local published contracts`);
