import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

// Shape types are derived only from the published contracts. Numeric, format,
// conditional and cross-message rules remain runtime validation obligations.
const directory = new URL('../packages/contracts/src/schemas/', import.meta.url);
const documents = new Map();
for (const file of readdirSync(directory).filter(file => file.endsWith('.schema.json')).sort()) {
  const bytes = readFileSync(new URL(file, directory));
  const schema = JSON.parse(bytes);
  documents.set(schema.$id, { schema, file, digest: createHash('sha256').update(bytes).digest('hex') });
}
const provider = 'https://lifestream.dev/contracts/provider-messages/1.0.0';
const common = 'https://lifestream.dev/contracts/protocol-common/1.0.0';
const seeds = [
  'CapabilitySnapshotRequest', 'CapabilitySnapshotResult', 'CapabilityInvocationRequest', 'CapabilityInvocationResult',
  'CapabilityStatusRequest', 'CapabilityStatusResult', 'CapabilityInvalidationRequest', 'CapabilityInvalidationEvent',
  'AuthorityRequest', 'AuthorityResult', 'AuthorityDispatchRequest', 'AuthorityDispatchResult',
  'GrantQueryRequest', 'GrantQueryResult', 'AuthorityInvalidationRequest', 'AuthorityInvalidationEvent'
];
const names = new Map(seeds.map(name => [`${provider}#/$defs/${name}`, name]));
for (const name of ['ArtifactRef', 'CallScope', 'Problem', 'SourceRevision']) names.set(`${common}#/$defs/${name}`, name);
const bodies = new Map();
const used = new Set();
const identifier = value => value.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => c?.toUpperCase() ?? '');
function reference(ref, base) {
  const absolute = new URL(ref, base).href;
  const [id, fragment = ''] = absolute.split('#');
  const key = fragment ? `${id}#${fragment}` : id;
  const document = documents.get(id);
  if (!document) throw new Error(`Unpublished schema reference: ${id}`);
  if (!names.has(key)) {
    const label = `${identifier(document.file.replace('.schema.json', ''))}_${identifier(fragment || 'Root')}`;
    if ([...names.values()].includes(label)) throw new Error(`Type name collision: ${label}`);
    names.set(key, label);
  }
  if (!bodies.has(key)) {
    let schema = document.schema;
    for (const part of fragment.split('/').slice(1)) schema = schema[decodeURIComponent(part).replaceAll('~1', '/').replaceAll('~0', '~')];
    if (schema === undefined) throw new Error(`Missing reference: ${key}`);
    bodies.set(key, ''); // recursive references resolve to their alias
    used.add(id);
    bodies.set(key, shape(schema, id));
  }
  return names.get(key);
}
function shape(schema, base) {
  if (schema === true) return 'unknown';
  if (schema === false) return 'never';
  if ('prefixItems' in schema || 'patternProperties' in schema || schema.$dynamicRef) throw new Error('Unsupported structural schema');
  const parts = [];
  if (schema.$ref) parts.push(reference(schema.$ref, base));
  if ('const' in schema) parts.push(JSON.stringify(schema.const));
  if (schema.enum) parts.push(`(${schema.enum.map(value => JSON.stringify(value)).join(' | ')})`);
  for (const key of ['oneOf', 'anyOf']) if (schema[key]) parts.push(`(${schema[key].map(s => shape(s, base)).join(' | ')})`);
  if (schema.allOf) parts.push(`(${schema.allOf.map(s => shape(s, base)).join(' & ')})`);
  if (Array.isArray(schema.type)) parts.push(`(${schema.type.map(type => shape({ ...schema, type }, base)).join(' | ')})`);
  else if (schema.type === 'object' || schema.properties) {
    const properties = Object.entries(schema.properties ?? {});
    const fields = properties.map(([name, value]) => `${JSON.stringify(name)}${schema.required?.includes(name) ? '' : '?'}: ${shape(value, base)};`);
    for (const name of schema.required ?? []) if (!Object.hasOwn(schema.properties ?? {}, name)) fields.push(`${JSON.stringify(name)}: unknown;`);
    if (schema.additionalProperties !== false) {
      // An index signature must also admit the named fields in an open object.
      const extra = schema.additionalProperties && typeof schema.additionalProperties === 'object' ? shape(schema.additionalProperties, base) : 'unknown';
      fields.push(`[key: string]: ${properties.length ? 'unknown' : extra};`);
    }
    parts.push(`{ ${fields.join(' ')} }`);
  } else if (schema.type === 'array') parts.push(`Array<${shape(schema.items ?? true, base)}>`);
  else if (schema.type) {
    const primitive = { string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' }[schema.type];
    if (!primitive) throw new Error(`Unsupported type: ${schema.type}`);
    parts.push(primitive);
  }
  return parts.length ? parts.map(p => `(${p})`).join(' & ') : 'unknown';
}
for (const key of [...names.keys()]) reference(key, provider);
const output = [
  '// Generated by scripts/generate-provider-types.mjs. Do not edit.',
  '// Shapes only: validate the canonical schemas and cross-message rules at runtime.',
  ...[...used].sort().map(id => `// ${documents.get(id).file} sha256:${documents.get(id).digest}`),
  ...[...bodies].sort(([a], [b]) => names.get(a) < names.get(b) ? -1 : names.get(a) > names.get(b) ? 1 : 0).map(([key, body]) => `export type ${names.get(key)} = ${body};`), ''
].join('\n');
const path = new URL('../packages/contracts/src/provider-messages.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Provider types are stale; run node scripts/generate-provider-types.mjs');
} else writeFileSync(path, output);
console.log(`Provider types: ${bodies.size} aliases from ${used.size} published schemas (${fileURLToPath(path)})`);
